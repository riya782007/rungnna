// Reads supabase/migrations/*.sql and lists every column each table has in the cloud.
// Used to write src/lib/columns.ts (node scripts/schema-columns.mjs --write) and by tests/columns.test.ts.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

export function columnsFromMigrations(dir) {
  const cols = {};
  const add = (t, c) => { (cols[t] ||= new Set()).add(c); };
  for (const f of readdirSync(dir).filter(f => f.endsWith(".sql")).sort()) {
    const s = readFileSync(dir + "/" + f, "utf8").replace(/--[^\n]*/g, "");
    for (const m of s.matchAll(/create table(?: if not exists)?\s+(?:public\.)?(\w+)\s*\(/gi)) {
      let i = m.index + m[0].length, depth = 1, body = "";
      for (; i < s.length && depth; i++) { const ch = s[i]; if (ch === "(") depth++; if (ch === ")") depth--; if (depth) body += ch; }
      let d = 0, cur = ""; const parts = [];
      for (const ch of body) { if (ch === "(") d++; if (ch === ")") d--; if (ch === "," && !d) { parts.push(cur); cur = ""; } else cur += ch; }
      parts.push(cur);
      for (const p of parts) { const w = p.trim().split(/[\s(]+/)[0]?.replace(/"/g, ""); if (w && !/^(primary|unique|constraint|foreign|check|exclude)$/i.test(w)) add(m[1], w); }
    }
    for (const m of s.matchAll(/alter table\s+(?:if exists\s+)?(?:only\s+)?(?:public\.)?(\w+)\s+([^;]*);/gi))
      for (const c of m[2].matchAll(/add column(?: if not exists)?\s+(\w+)/gi)) add(m[1], c[1]);
    // do-blocks that add one column to a list of tables: foreach t in array array['a','b'] loop execute format('alter table ... %I add column ... x
    for (const m of s.matchAll(/foreach\s+\w+\s+in\s+array\s+array\[([^\]]*)\]\s+loop([\s\S]*?)end\s+loop/gi))
      for (const c of m[2].matchAll(/alter table[^']*%I\s+add column(?: if not exists)?\s+(\w+)/gi))
        for (const t of m[1].matchAll(/'(\w+)'/g)) add(t[1], c[1]);
  }
  return Object.fromEntries(Object.entries(cols).sort().map(([t, s]) => [t, [...s].sort()]));
}

if (process.argv.includes("--write")) {
  const cols = columnsFromMigrations(new URL("../supabase/migrations", import.meta.url).pathname);
  const body = Object.entries(cols).map(([t, c]) => `  ${t}: ${JSON.stringify(c)},`).join("\n");
  writeFileSync(new URL("../src/lib/columns.ts", import.meta.url),
`/* GENERATED by scripts/schema-columns.mjs --write from supabase/migrations. Do not edit by hand.
   Sync sends only these columns, so a field that exists only on this device can never stop the shop's sync. */
export const COLUMNS: Record<string, readonly string[]> = {
${body}
};
`);
  console.log("wrote src/lib/columns.ts");
}
